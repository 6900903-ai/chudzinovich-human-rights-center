import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { parseYoutubeAtom, validateYoutubeSnapshot, YOUTUBE_CHANNEL_ID } from '../scripts/lib/youtube.mjs';

const root=new URL('../',import.meta.url).pathname;
const fixture=`<?xml version="1.0" encoding="UTF-8"?><feed xmlns:yt="http://www.youtube.com/xml/schemas/2015"><yt:channelId>${YOUTUBE_CHANNEL_ID}</yt:channelId><title>ТОЧКА НЕВОЗВРАТА Чудинович Юра</title><entry><yt:videoId>AbCdEf123_4</yt:videoId><title>Тестовое видео &amp; CHUDO</title><published>2026-08-29T10:00:00+00:00</published><updated>2026-08-29T11:00:00+00:00</updated></entry></feed>`;
const parsed=parseYoutubeAtom(fixture,'2026-08-29T12:00:00Z');
assert.equal(parsed.videos.length,1);
assert.equal(parsed.videos[0].video_id,'AbCdEf123_4');
assert.equal(parsed.videos[0].title,'Тестовое видео & CHUDO');
assert.equal(parsed.videos[0].url,'https://www.youtube.com/watch?v=AbCdEf123_4');
const suffixFixture=fixture.replace(`<yt:channelId>${YOUTUBE_CHANNEL_ID}</yt:channelId>`,`<yt:channelId>${YOUTUBE_CHANNEL_ID.slice(2)}</yt:channelId>`);
assert.doesNotThrow(()=>parseYoutubeAtom(suffixFixture,'2026-08-29T12:00:00Z'));
const wrongFixture=fixture.replace(YOUTUBE_CHANNEL_ID,'ZZTXAwovvaec4w9ztbggWMEQ');
assert.throws(()=>parseYoutubeAtom(wrongFixture,'2026-08-29T12:00:00Z'),/CHANNEL_MISMATCH/);
assert.throws(()=>parseYoutubeAtom(fixture.replace('<feed','<!DOCTYPE x [<!ENTITY x SYSTEM "file:///etc/passwd">]><feed')),/DTD_FORBIDDEN/);
const stored=JSON.parse(await readFile(join(root,'data/public/youtube.json'),'utf8'));
assert.doesNotThrow(()=>validateYoutubeSnapshot(stored));
assert.ok(stored.videos.length>=1);
const current=stored.videos[0];
for(const script of ['build.mjs','build-youtube-pages.mjs','build-global-search.mjs'])execFileSync(process.execPath,[join(root,'scripts',script)],{stdio:'inherit'});
const index=await readFile(join(root,'_site/videos/index.html'),'utf8');
const item=await readFile(join(root,`_site/videos/${current.video_id}/index.html`),'utf8');
const home=await readFile(join(root,'_site/index.html'),'utf8');
const search=JSON.parse(await readFile(join(root,'_site/assets/search/ru.json'),'utf8'));
assert.ok(index.includes(stored.channel_title));
assert.ok(index.includes(`/videos/${current.video_id}/`));
assert.ok(item.includes('"@type":"VideoObject"'));
assert.ok(item.includes(current.url));
assert.ok(!item.includes('<iframe'));
assert.ok(home.includes('home-youtube-section'));
assert.ok(search.some(x=>x.t==='video'&&x.u===`/videos/${current.video_id}/`));
console.log(`YOUTUBE_INTEGRATION_TEST=PASS videos=${stored.videos.length} parser=PASS suffix_channel_id=PASS dtd_block=PASS pages=PASS search=PASS runtime_embed=ZERO`);
